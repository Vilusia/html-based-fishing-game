const fs = require('fs'), path = require('path');
const SKIP = new Set(['.git', 'node_modules', 'vendor', 'Music', 'tests']);
const EXT = new Set(['.js', '.css', '.html', '.ps1']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) { if (!SKIP.has(e.name)) walk(path.join(dir, e.name)); }
    else if (EXT.has(path.extname(e.name))) files.push(path.join(dir, e.name));
  }
})('.');

const NAME = '([A-Za-z_$][\\w$]*)';
const strict = new RegExp('^(?:async\\s+)?(?:function\\*?\\s+' + NAME + '|class\\s+' + NAME +
  '|(?:const|let|var)\\s+' + NAME + '\\s*=|(?:window|globalThis)\\.' + NAME + '\\s*=)');
const loose = new RegExp(strict.source.replace('^', '^(?:\\t| {1,4})'));

function scan(lines, re) {
  const hits = [];
  lines.forEach((l, i) => {
    if (l.length > 2000) return;
    const m = re.exec(l);
    if (m) hits.push(`${m[1] || m[2] || m[3] || m[4]}(${i + 1})`);
  });
  return hits;
}

const out = ['# PROJECT_MAP.md', '',
  'Auto-generated by make-map.js. Names show (line number). Rerun after big edits.', ''];
for (const f of files.sort()) {
  const src = fs.readFileSync(f, 'utf8');
  const lines = src.split('\n');
  const ext = path.extname(f);
  out.push(`## ${f.replace(/\\/g, '/')} (${(Buffer.byteLength(src) / 1024).toFixed(1)} KB, ${lines.length} lines)`);
  out.push('Purpose: (fill in)');
  if (ext === '.js') {
    let hits = scan(lines, strict);
    if (!hits.length) hits = scan(lines, loose);
    const shown = hits.slice(0, 40).join(', ');
    out.push('Defines: ' + (shown || '(nothing found)') +
      (hits.length > 40 ? `, ...and ${hits.length - 40} more` : ''));
  } else if (ext === '.html') {
    const scripts = [...src.matchAll(/<script[^>]*\ssrc=["']([^"']+)["']/g)].map(m => m[1]);
    const css = [...src.matchAll(/<link[^>]*href=["']([^"']+\.css[^"']*)["']/g)].map(m => m[1]);
    const inline = [...src.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)]
      .reduce((n, m) => n + m[1].length, 0);
    out.push('Scripts in load order: ' + (scripts.join(', ') || 'none'));
    out.push('Stylesheets: ' + (css.join(', ') || 'none'));
    out.push(`Inline script: ${(inline / 1024).toFixed(1)} KB`);
  }
  out.push('');
}
fs.writeFileSync('PROJECT_MAP.md', out.join('\n'));
console.log('Wrote PROJECT_MAP.md');