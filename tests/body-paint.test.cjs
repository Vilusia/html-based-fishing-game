function bodyPaintRules() {
    const start = core.indexOf('// Body paint is a compact');
    const end = core.indexOf('const DEFAULT_SAVE_STATE', start);
    const c = vm.createContext({ window: {} });
    vm.runInContext(core.slice(start, end), c);
    return c.window.BodyPaint;
}

const BP = bodyPaintRules();
const blank = '.'.repeat(BP.size);

test('body paint is a bounded indexed bitmap with a clear empty state', () => {
    assert.equal(BP.width, 24);
    assert.equal(BP.height, 23);
    assert.equal(BP.palette.length, 16);
    assert.equal(BP.customIndex, 'x');
    const painted = blank.slice(0, 20) + 'f' + blank.slice(21);
    assert.equal(BP.normalize(painted), painted);
    assert.equal(BP.normalize(BP.normalize(painted).toUpperCase()), painted);
    const custom = blank.slice(0, 12) + 'x' + blank.slice(13);
    assert.equal(BP.normalize(custom), custom);
    assert.equal(BP.normalizeColor('#A1B2C3'), '#a1b2c3');
    assert.equal(BP.normalizeColor('red'), '#ffffff');
    assert.equal(BP.normalizeColor(null), '#ffffff');
    for (const bad of [null, {}, 'https://example.com/paint.png', '<svg>', '0'.repeat(551), 'g'.repeat(552), '0'.repeat(553)]) {
        assert.equal(BP.normalize(bad), '');
    }
    assert.equal(BP.normalize(''), '');
});

