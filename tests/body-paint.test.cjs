test('body paint renders palette and custom-colored pixels, including side textures', () => {
    const start = ui.indexOf('function drawBodyPaint(');
    const end = ui.indexOf('// ---------------------------------------------------------------------------', start);
    assert(start > 0 && end > start);
    const calls = [];
    const ctx = { fillStyle: '', fillRect(x, y, w, h) { calls.push([this.fillStyle, x, y, w, h]); } };
    const c = vm.createContext({ window: { BodyPaint: BP } });
    vm.runInContext(ui.slice(start, end), c);
    const painted = blank.slice(0, 0) + '0' + blank.slice(1, 552 - 2) + 'x' + 'f';
    c.drawBodyPaint(ctx, painted, false, '#123456');
    assert.deepEqual(calls[0], [BP.palette[0], 20, 35, 1, 1]);
    assert.deepEqual(calls[1], ['#123456', 20 + BP.width - 2, 35 + BP.height - 1, 1, 1]);
    assert.deepEqual(calls.at(-1), [BP.palette[15], 43, 57, 1, 1]);
    calls.length = 0;
    c.drawBodyPaint(ctx, 'x' + blank.slice(1), false, '#abcdef', 0, 0);
    assert.deepEqual(calls[0], ['#abcdef', 0, 0, 1, 1]);
    calls.length = 0;
    c.drawBodyPaint(ctx, 'x' + blank.slice(1), false, '#abcdef', 0, 0, 4, 3);
    assert.deepEqual(calls[0], ['#abcdef', 0, 0, 4, 3]);
    assert(ui.includes('createBodySideTexture'));
    assert(ui.includes('assets.torsoLeft=createBodySideTexture'));
    assert(ui.includes('assets.torsoRight=createBodySideTexture'));
    assert(ui.includes('assets.headLeft=createBodySideTexture'));
    assert(ui.includes('assets.headRight=createBodySideTexture'));
    assert(ui.includes("crop(front,16,8,32,26,cfg.bodyPaintHeadFront||'')"));
});

